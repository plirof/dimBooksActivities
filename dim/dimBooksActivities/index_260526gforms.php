function detectType($data) {
    if (isset($data['questions']))      return 'quiz';
    if (isset($data['categories']) && !isset($data['items']))  return 'drag-categories';
    if (isset($data['steps']))          return 'drag-order';
    if (isset($data['pairs']) && !isset($data['zoneLabels']))  return 'memory';
    if (isset($data['targets']))        return 'click-game';
    if (isset($data['items']) && isset($data['speed']) && !isset($data['spawnInterval'])) return 'falling-letters';
    if (isset($data['palette']))        return 'canvas-pixels';
    if (isset($data['winScore']) && !isset($data['items']))    return 'arcade-game';
    if (isset($data['rounds']) && isset($data['range'])) return 'guess-number';
    if (isset($data['qrItems']))        return 'qr-scanner';
    if (isset($data['filterMode']))     return 'spreadsheet-filter';
    if (isset($data['balloons']))       return 'balloon-pop';
    if (isset($data['items']) && isset($data['spawnInterval']) && isset($data['lives'])) return 'catch-falling';
    if (isset($data['blocks']) && isset($data['correctOrder'])) return 'flowchart';
    if (isset($data['words']) && isset($data['maxWrong'])) return 'hangman';
    if (isset($data['pairs']) && isset($data['zoneLabels'])) return 'matching-lines';
    if (isset($data['gridSize']) && isset($data['timeLimit'])) return 'maze';
    if (isset($data['centralTopic']))   return 'mind-map';
    if (isset($data['sentences']))      return 'sentence-build';
    if (isset($data['categories']) && isset($data['items']) && isset($data['duration'])) return 'sorting-speed';
    if (isset($data['texts']) && !isset($data['challenges'])) return 'speed-type';
    if (isset($data['rounds']) && !isset($data['range']) && !isset($data['segments']) && !isset($data['colors']) && !isset($data['instructions'])) return 'spot-error';
    if (isset($data['words']) && isset($data['raceLength'])) return 'typing-race';
    if (isset($data['circleA']))        return 'venn-diagram';
    if (isset($data['words']) && !isset($data['maxWrong']) && !isset($data['directions']) && !isset($data['raceLength'])) return 'word-scramble';
    if (isset($data['gridSize']) && isset($data['targets'])) return 'grid-game';
    if (isset($data['winScore']) && isset($data['items']))    return 'arcade-game';
    return 'unknown';
}

function activityCountUnique($activities) {
    $quizTypes = ['quiz','0quiz_basket','0quiz_penalty','0quiz_basket_game','0quiz_soccer_game','0quiz_duel_basket','0quiz_runner'];
    $seen = [];
    $count = 0;
    foreach ($activities as $a) {
        if (in_array($a['type'], $quizTypes)) {
            $key = ($a['filename'] ?? '') . '|' . ($a['lesson'] ?? '');
            if (!isset($seen[$key])) {
                $seen[$key] = true;
                $count++;
            }
        } else {
            $count++;
        }
    }
    return $count;
}

function scanActivities($basePath, $dir) {
    $activitiesPath = $basePath . '/' . $dir . '/activities/';
    $results = [];
    if (!is_dir($activitiesPath)) return $results;

    $files = glob($activitiesPath . '*.json');
    sort($files);

    foreach ($files as $file) {
        $filename = basename($file);
        $json = @json_decode(file_get_contents($file), true);
        if (!$json) continue;

        $title = $json['title'] ?? '';
        $subtitle = $json['subtitle'] ?? '';

        if (preg_match('/dim[A-Z]+-les(\d+)-([a-z-]+)-([a-zA-Z0-9]{3})\.json/', $filename, $m)) {
            $lesson = (int)$m[1];
            $type = $m[2];
            $act = $m[3];
        } else {
            $lesson = 0;
            $act = 0;
            $type = detectType($json);
        }

        $baseEntry = [
            'filename'  => $filename,
            'lesson'    => $lesson,
            'act'       => $act,
            'type'      => $type,
            'title'     => $title,
            'subtitle'  => $subtitle,
            'dataPath'  => '../' . $dir . '/activities/' . $filename,
        ];

        if ($type === 'quiz') {
            $entry = $baseEntry;
            $entry['type'] = '0quiz_basket';
            $results[] = $entry;

            $entry = $baseEntry;
            $entry['type'] = '0quiz_penalty';
            $results[] = $entry;

            $entry = $baseEntry;
            $entry['type'] = '0quiz_basket_game';
            $results[] = $entry;

            $entry = $baseEntry;
            $entry['type'] = '0quiz_soccer_game';
            $results[] = $entry;


            $entry = $baseEntry;
            $entry['type'] = '0quiz_duel_basket';
            $results[] = $entry;

            $entry = $baseEntry;
            $entry['type'] = '0quiz_runner';
            $results[] = $entry;
        }

        $results[] = $baseEntry;
    }
    return $results;
}

function scanCustomHtml($basePath, $classKey) {
    $uniquePath = $basePath . '/activities-unique/';
    $results = [];
    if (!is_dir($uniquePath)) return $results;

    $patterns = [
        $uniquePath . 'dim' . $classKey . '_les*act*.html',
        $uniquePath . 'dim' . $classKey . '-les*-custom-*.html',
    ];

    $allFiles = [];
    foreach ($patterns as $pattern) {
        $files = glob($pattern);
        if ($files) $allFiles = array_merge($allFiles, $files);
    }
    $allFiles = array_unique($allFiles);
    sort($allFiles);

    foreach ($allFiles as $file) {
        $filename = basename($file);
        $content = @file_get_contents($file, false, null, 0, 2000);

        $title = '';
        if (preg_match('/<title>(.*?)<\/title>/i', $content, $m)) {
            $title = html_entity_decode(trim($m[1]), ENT_QUOTES | ENT_HTML5);
        }

        if (preg_match('/dim' . $classKey . '_les(\d+)act(\d+)/', $filename, $m)) {
            $lesson = (int)$m[1];
            $act = (int)$m[2];
        } elseif (preg_match('/dim' . $classKey . '-les(\d+)-custom-(.+)\.html$/', $filename, $m)) {
            $lesson = (int)$m[1];
            $act = 0;
        } else {
            $lesson = 0;
            $act = 0;
        }

        $results[] = [
            'filename'  => $filename,
            'lesson'    => $lesson,
            'act'       => $act,
            'type'      => 'custom',
            'title'     => $title,
            'subtitle'  => '',
            'htmlPath'  => 'activities-unique/' . $filename,
        ];
    }
    return $results;
}

